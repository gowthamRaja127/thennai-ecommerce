// Regenerates supabase/seed.sql from SEED_PRODUCTS:  npx tsx scripts/generate-seed.ts
import { writeFileSync } from 'node:fs';
import { SEED_PRODUCTS } from '../src/data/products.ts';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (a: string[]) => (a.length ? `array[${a.map(q).join(', ')}]` : `'{}'::text[]`);

const rows = SEED_PRODUCTS.map(
  (p) => `  (${[
    q(p.id), q(p.name), q(p.shortName), q(p.category), q(p.badge), p.price, p.compareAt ?? 'null',
    q(p.tagline), q(p.description), arr(p.contents), arr(p.howTo), arr(p.details), arr(p.variants),
    `${q(JSON.stringify(p.media))}::jsonb`, q(p.cta), p.active, p.sortOrder,
  ].join(', ')})`,
);

const sql = `-- Launch catalogue. Generated by scripts/generate-seed.ts; safe to re-run (existing products are left untouched).
insert into public.products
  (id, name, short_name, category, badge, price, compare_at, tagline, description, contents, how_to, details, variants, media, cta, active, sort_order)
values
${rows.join(',\n')}
on conflict (id) do nothing;
`;
writeFileSync('supabase/seed.sql', sql);
console.log(`wrote ${SEED_PRODUCTS.length} products to supabase/seed.sql`);
